# update-model-prices.py — regenerates Devgentic/Resources/ModelPrices.json, the ONLY writer of it.
#
# Source: LiteLLM's model_prices_and_context_window.json (MIT; see THIRD_PARTY_NOTICES.md). Kept:
# chat models of the three providers we price from a list (Anthropic, OpenAI, Gemini), and only the
# fields `ModelPriceList` reads. OpenRouter is NOT kept: it reports each call's cost itself.
#
# Run before each release:   scripts/update-model-prices.py [--ref <commit-or-branch>]
# The app never fetches prices at runtime.

import argparse
import datetime
import json
import os
import sys
import urllib.request

REPO = "BerriAI/litellm"
PATH = "model_prices_and_context_window.json"
PROVIDERS = {"anthropic", "openai", "gemini"}
FIELDS = [
    "input_cost_per_token",
    "output_cost_per_token",
    "cache_read_input_token_cost",
    "cache_creation_input_token_cost",
    "input_cost_per_token_above_200k_tokens",
    "output_cost_per_token_above_200k_tokens",
    "cache_read_input_token_cost_above_200k_tokens",
    "cache_creation_input_token_cost_above_200k_tokens",
]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Devgentic", "Resources", "ModelPrices.json")


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "devgentic-update-model-prices"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def resolve_commit(ref):
    """The commit `ref` points at, so the file records exactly what it was built from."""
    try:
        data = json.loads(fetch(f"https://api.github.com/repos/{REPO}/commits?path={PATH}&sha={ref}&per_page=1"))
        return data[0]["sha"]
    except Exception as error:  # the rate-limited API is a nicety; the raw file is what matters
        print(f"warning: could not resolve '{ref}' to a commit ({error}); recording the ref itself", file=sys.stderr)
        return ref


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--ref", default="main", help="LiteLLM commit or branch (default: main)")
    args = parser.parse_args()

    commit = resolve_commit(args.ref)
    source = json.loads(fetch(f"https://raw.githubusercontent.com/{REPO}/{commit}/{PATH}"))

    models = {}
    for name, entry in source.items():
        if not isinstance(entry, dict) or entry.get("litellm_provider") not in PROVIDERS or entry.get("mode") != "chat":
            continue
        if "input_cost_per_token" not in entry or "output_cost_per_token" not in entry:
            continue
        kept = {field: entry[field] for field in FIELDS if isinstance(entry.get(field), (int, float))}
        kept["provider"] = entry["litellm_provider"]
        models[name] = kept

    if not all(any(m["provider"] == p for m in models.values()) for p in PROVIDERS):
        sys.exit("error: a provider has no models — the source format may have changed; not writing")

    output = {
        "_source": {
            "url": f"https://github.com/{REPO}/blob/{commit}/{PATH}",
            "commit": commit,
            "fetched": datetime.date.today().isoformat(),
            "license": "MIT (LiteLLM) — see THIRD_PARTY_NOTICES.md",
            "note": "Generated by scripts/update-model-prices.py. Do not edit by hand.",
        },
        "models": dict(sorted(models.items())),
    }
    with open(OUT, "w", encoding="utf-8") as handle:
        json.dump(output, handle, indent=1, sort_keys=False)
        handle.write("\n")
    counts = {p: sum(1 for m in models.values() if m["provider"] == p) for p in sorted(PROVIDERS)}
    print(f"wrote {os.path.relpath(OUT)}: {len(models)} models {counts}, commit {commit[:12]}")


if __name__ == "__main__":
    main()
