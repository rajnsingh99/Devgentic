//  UserDefaults-backed configuration for the notification system.
//  Tracks global enable, per-channel enable, and per-conversation overrides.
//

import Foundation
import SwiftUI
import os

private let logger = DGLogger(category: "NotificationConfiguration")

@Observable @MainActor
final class NotificationConfiguration {

    static let shared = NotificationConfiguration()

    /// The master switch. Backed directly by `UserDefaults`, with observation wired by hand.
    ///
    /// ⚠️ THIS WAS `@ObservationIgnored @AppStorage(...)` AND THAT SHAPE IS BROKEN IN A CLASS.
    /// `AppStorage` is a `DynamicProperty`, and `DynamicProperty.update()` is only called for a
    /// `View` — never for a property declared on a class. Two independent failures followed, both
    /// reproduced in `MasterSwitchObservabilityTests` before this was changed:
    ///
    ///   1. IT CACHED. The wrapper read the store once and answered from its own copy forever, so
    ///      the pane could report notifications ON while `UserDefaults` — and therefore
    ///      `NotificationDispatcher.dispatch()`, which reads the store live — said OFF. The pane
    ///      showed something other than what was actually enforced.
    ///   2. IT NOTIFIED NOBODY. `@ObservationIgnored` removed it from `@Observable`'s tracking and
    ///      `AppStorage` on a class publishes nothing itself, so a SwiftUI body reading it
    ///      registered no dependency and was never invalidated. Every control gated on it rendered
    ///      once and then held a stale value.
    ///
    /// ⚠️ THE GETTER READS THROUGH `NotificationGatePolicy`, the same function the dispatcher uses.
    /// That is what makes "the pane shows what is enforced" true by construction rather than by
    /// convention — there is now one rule AND one state, not one rule over two copies.
    ///
    /// ⚠️ `access` / `withMutation` are generated by the `@Observable` macro. They are what a
    /// stored property gets for free and a computed one must ask for; without them this would read
    /// correctly but still never invalidate a view.
    var isGloballyEnabled: Bool {
        get {
            access(keyPath: \.isGloballyEnabled)
            return NotificationGatePolicy.isGloballyEnabled(in: .standard)
        }
        set {
            withMutation(keyPath: \.isGloballyEnabled) {
                UserDefaults.standard.set(newValue, forKey: AppSettings.notificationsEnabledKey)
            }
        }
    }

    /// Per-conversation override. `true` = force enabled, `false` = force disabled, absent = use global.
    var perConversationOverrides: [UUID: Bool] = [:] {
        didSet { persistOverrides() }
    }

    private init() {
        loadOverrides()
    }

    /// Check whether notifications should fire for a given conversation.
    ///
    /// ⚠️ THE UI'S READ OF THE SAME DECISION `dispatch()` ENFORCES. The rule itself lives in
    /// `NotificationGatePolicy` so the settings pane and the dispatcher cannot drift apart; this
    /// supplies the observed in-memory state, `dispatch()` supplies the persisted state.
    ///
    /// ⚠️ This is no longer the enforcement point for any caller. Delivery is gated inside
    /// `NotificationDispatcher.dispatch(_:)`, which every notification passes through.
    func isNotificationEnabled(for conversationID: UUID?) -> Bool {
        NotificationGatePolicy.shouldDeliver(
            globallyEnabled: isGloballyEnabled,
            override: conversationID.flatMap { perConversationOverrides[$0] }
        )
    }

    /// Set or clear a per-conversation override.
    func setOverride(_ enabled: Bool?, for conversationID: UUID) {
        if let enabled = enabled {
            perConversationOverrides[conversationID] = enabled
        } else {
            perConversationOverrides.removeValue(forKey: conversationID)
        }
    }

    // MARK: - Persistence

    // ⚠️ BOTH HALVES DELEGATE TO THE SHARED CODEC. `NotificationDispatcher` decodes this same key
    // from the actor, so the stored shape has exactly one definition; a second copy here is how the
    // actor and the UI would come to disagree about one conversation.
    private func persistOverrides() {
        if let data = NotificationGatePolicy.encodeOverrides(perConversationOverrides) {
            UserDefaults.standard.set(data, forKey: AppSettings.notificationPerConversationKey)
        }
    }

    private func loadOverrides() {
        let stored = NotificationGatePolicy.decodeOverrides()
        guard !stored.isEmpty else { return }
        perConversationOverrides = stored
    }
}
